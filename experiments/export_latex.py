def rocchio_macros(registered: Dict, result: Dict) -> List[str]:
    """The figures the Rocchio section quotes."""
    outcomes = result["outcomes"]
    lines = [
        r"\newcommand{\RocchioK}{%d}" % result["k"],
        r"\newcommand{\RocchioHeld}{%d}" % sum(o["held"] for o in outcomes),
        r"\newcommand{\RocchioPredictions}{%d}" % len(outcomes),
        r"\newcommand{\RocchioRho}{%+.3f}" % result["per_class"]["rho"],
        r"\newcommand{\RocchioRhoPStat}{%s}" % p_stat(result["per_class"]["p"]),
        r"\newcommand{\RocchioRegistered}{%s}" % registered["registered_at"][:10],
    ]
    for name, stem in ROCCHIO_MACRO_NAME.items():
        r = result["corpora"][name]
        lines += [
            r"\newcommand{\Rocchio%sAlign}{%+.3f}" % (stem, registered["mean_alignment_change"][name]),
            r"\newcommand{\Rocchio%sGain}{%+.1f}" % (stem, r["gain_pp"]),
            r"\newcommand{\Rocchio%sPStat}{%s}" % (stem, p_stat(r["mcnemar"]["p_value"])),
            r"\newcommand{\Rocchio%sTerse}{%s\%%}" % (stem, pct(r["top1_terse"])),
            r"\newcommand{\Rocchio%sMoved}{%s\%%}" % (stem, pct(r["top1_rocchio"])),
        ]
    return lines


def effects_table(effects: Dict) -> str:
    """Appendix: every headline comparison with its interval and its Holm-adjusted p."""
    rows, group = [], None
    for t in effects["tests"]:
        if t["group"] != group:
            group = t["group"]
            rows.append(r"\midrule" if rows else "")
            rows.append(r"\multicolumn{5}{@{}l}{\emph{%s}} \\" % escape(group))
        if "ci95" in t:
            gain = f"${t['gain_pp']:+.1f}$ [${t['ci95'][0]:+.1f}$, ${t['ci95'][1]:+.1f}$]"
            n = str(t["n"])
        elif "gain_pp" in t:
            gain, n = f"${t['gain_pp']:+.1f}$", "--"
        else:
            gain, n = "--", "--"
        rows.append(" & ".join([escape(t["label"]), n, gain, p_cell(t["p"]), p_cell(t["p_holm"])]) + r" \\")
    return "\n".join([
        PREAMBLE, r"\begin{table*}[t]", r"\centering", r"\small",
        r"\begin{tabular}{@{}lrlrr@{}}", r"\toprule",
        r"Comparison & $n$ & Difference in points [95\% CI] & $p$ & Holm $p$ \\",
        *[r for r in rows if r], r"\bottomrule", r"\end{tabular}",
        r"\caption{Every comparison the paper reports as a finding. Differences are in Top-1 "
        r"percentage points (Top-3 where stated), oriented as named; intervals are percentile "
        r"bootstrap over documents, drawn from the discordant counts (the selection-rule results "
        r"keep no counts, so they have none); $p$ is the exact McNemar "
        r"test (Spearman for the correlations), and Holm $p$ corrects over all \EffectTests\ tests.}",
        r"\label{tab:effects}", r"\end{table*}", "",
    ])


def effects_macros(effects: Dict) -> List[str]:
    lost = effects["lost_to_correction"]
    return [
        r"\newcommand{\EffectTests}{%d}" % effects["n_tests"],
        r"\newcommand{\EffectNominal}{%d}" % effects["nominally_significant"],
        r"\newcommand{\EffectHolm}{%d}" % effects["significant_after_holm"],
        r"\newcommand{\EffectLostList}{%s}" % ("none" if not lost else "; ".join(escape(x) for x in lost)),
    ]


def compute_macros(compute: Dict) -> List[str]:
    """What a complete reproduction costs, as recorded by run.py."""
    return [
        r"\newcommand{\ReproduceMinutes}{%d}" % max(1, round(compute["wall_clock_seconds"] / 60)),
        r"\newcommand{\ReproduceCPU}{%s}" % escape(compute["cpu"]),
        r"\newcommand{\ReproduceCores}{%d}" % compute["cpu_count"],
    ]


def macros(baselines: Dict, error_report: Dict, study: Dict, search: Dict,
           reuters: Dict, news: Dict, derived: List[str]) -> str:
    """Numbers the prose cites, as macros, so the text cannot drift either."""
    systems = {s["key"]: s for s in baselines["systems"]}
    conditions = list(study["conditions"].values())
    align = search["correlations"]["alignment_gain"]
    extra = [
        r"\newcommand{\DescTerse}{%s\%%}" % pct(conditions[0]["top1_accuracy"]),
        r"\newcommand{\DescTranslated}{%s\%%}" % pct(conditions[1]["top1_accuracy"]),
        r"\newcommand{\DescRich}{%s\%%}" % pct(conditions[2]["top1_accuracy"]),
        r"\newcommand{\LanguageEffect}{%+.1f}" % study["language_effect"]["gain_pp"],
        r"\newcommand{\LanguageP}{%.2f}" % study["language_effect"]["p_value"],
        r"\newcommand{\ContentEffect}{%+.1f}" % study["content_effect"]["gain_pp"],
        r"\newcommand{\AlignRho}{%+.3f}" % align["rho"],
        r"\newcommand{\AlignP}{%.3f}" % align["p"],
        r"\newcommand{\NCLASSES}{%d}" % search["n_classes"],
        r"\newcommand{\ReutersGain}{%+.1f}" % reuters["defining_the_class"]["gain_pp"],
        r"\newcommand{\ReutersCodeGain}{%+.1f}" % reuters["spelling_the_label_out"]["gain_pp"],
        r"\newcommand{\NewsGain}{%+.1f}" % news["defining_the_class"]["gain_pp"],
        r"\newcommand{\NewsP}{%.2f}" % news["defining_the_class"]["p_value"],
    ]
    full = systems.get("full", {}).get("sector", {})
    tfidf = systems.get("tfidf-nace", {}).get("sector", {})
    ci = full.get("top1_ci95") or [0, 0]
    return "\n".join(
        [
            PREAMBLE,
            r"\newcommand{\NEVAL}{%d}" % full.get("n", 0),
            r"\newcommand{\OursTopOne}{%s\%%}" % pct(full.get("top1_accuracy")),
            r"\newcommand{\OursTopThree}{%s\%%}" % pct(full.get("top3_accuracy")),
            r"\newcommand{\OursFOne}{%s}" % num(full.get("f1_macro")),
            r"\newcommand{\OursCI}{[%s, %s]}" % (pct(ci[0]), pct(ci[1])),
            r"\newcommand{\TfidfTopOne}{%s\%%}" % pct(tfidf.get("top1_accuracy")),
            r"\newcommand{\TfidfFOne}{%s}" % num(tfidf.get("f1_macro")),
            r"\newcommand{\NErrors}{%d}" % error_report.get("n_errors", 0),
            r"\newcommand{\CorpusSize}{9{,}993}",
            r"\newcommand{\EvalShareOfCorpus}{%.0f\%%}" % (100 * full.get("n", 0) / CORPUS_SIZE),
            r"\newcommand{\NSections}{21}",
            *extra,
            *derived,
            "",
        ]
    )


def main() -> int:
    TABLES_DIR.mkdir(parents=True, exist_ok=True)

    baselines = load("baselines")
    ablation = load("ablation")
    error_report = load("error_analysis")
    study = load("description_study")
    search = load("predictor_search")
    reuters = load("reuters")
    news = load("replication_20newsgroups")
    verification = load("verification_report")
    retired = load("retired_eval_set")
    predictions = load("ablation_predictions")
    split = json.loads((ROOT / "data" / "evaluation" / "split.json").read_text(encoding="utf-8"))
    with (RESULTS_DIR / "verification_sample_pilot.csv").open(encoding="utf-8") as handle:
        pilot = [r for r in csv.DictReader(handle) if r["true_sector"].strip()]

    corpora = corpus_effects(study, search, reuters, news)
    derived = derived_macros(ablation, predictions, split, error_report, search,
                             verification, pilot, retired, corpora)
    derived += robustness_macros(load("robustness"))
    derived += compute_macros(load("compute"))
    effects = load_optional("effect_sizes")
    if effects:
        derived += effects_macros(effects)
    registered, rocchio = load_optional("rocchio_preregistration"), load_optional("rocchio")
    if registered and rocchio:
        derived += rocchio_macros(registered, rocchio)
    llm = load_optional("llm_baseline")
    if llm and llm.get("complete"):
        derived += llm_macros(llm)
    else:
        llm = None

    written = {
        "baselines.tex": baseline_table(baselines["systems"], llm),
        "ablation.tex": ablation_table(ablation["systems"]),
        "errors.tex": error_table(error_report),
        "descriptions.tex": description_study_table(study),
        "corpora.tex": corpora_table(study, search, reuters, news),
        "alignment_figure.tex": alignment_figure(search),
        **({"rocchio.tex": rocchio_table(registered, rocchio)} if registered and rocchio else {}),
        **({"effects.tex": effects_table(effects)} if effects else {}),
        "predictors.tex": predictors_table(search),
        "macros.tex": macros(baselines, error_report, study, search, reuters, news, derived),
    }
    for name, content in written.items():
        (TABLES_DIR / name).write_text(content, encoding="utf-8")
        print(f"  {Path('paper/tables') / name}")

    print(f"\nWrote {len(written)} files. The paper \\inputs them; nothing to copy by hand.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
