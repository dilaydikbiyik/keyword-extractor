FIGURE_YMIN = -1.0
SERIES = {"NACE": ("NACE sections", "nace", "*", "3pt"),
          "20NG": ("20 Newsgroups classes", "news", "triangle*", "3.6pt")}


def alignment_figure(search: Dict) -> str:
    """Per-class alignment change against the share of headroom captured.

    Colours are slots 1 and 2 of the validated categorical palette (all-pairs
    CVD separation 24.7 on white); marker shape repeats the distinction for
    grayscale print. A class below the plotted range is pinned to the lower
    edge with its true value written beside it rather than silently clipped.
    """
    usable = [r for r in search["classes"] if r["recall_terse"] < 0.999]

    def headroom_share(r):
        return (r["recall_rich"] - r["recall_terse"]) / (1 - r["recall_terse"])

    plots, off_scale = [], []
    for dataset, (legend, colour, mark, size) in SERIES.items():
        points = []
        for r in (r for r in usable if r["dataset"] == dataset):
            y = headroom_share(r)
            if y < FIGURE_YMIN:
                off_scale.append((r, y, colour, mark, size))
            else:
                points.append(f"({r['alignment_gain']:.4f},{y:.4f})")
        plots += [
            rf"\addplot[only marks, mark={mark}, mark size={size}, "
            rf"mark options={{fill={colour}, draw=white, line width=0.6pt}}] coordinates {{",
            "  " + " ".join(points),
            "};",
            rf"\addlegendentry{{{legend}}}",
        ]
    for r, y, colour, mark, size in off_scale:
        x = r["alignment_gain"]
        plots += [
            rf"\addplot[only marks, forget plot, mark={mark}, mark size={size}, "
            rf"mark options={{fill=white, draw={colour}, line width=0.9pt}}] "
            rf"coordinates {{({x:.4f},{FIGURE_YMIN})}};",
            rf"\node[font=\scriptsize, text=ink2, anchor=west] at (axis cs:{x + 0.012:.4f},{FIGURE_YMIN}) "
            rf"{{{escape(r['class'])}: ${y:+.1f}$, off scale}};",
        ]
    lines = [
        PREAMBLE,
        r"\definecolor{nace}{HTML}{2A78D6}",
        r"\definecolor{news}{HTML}{EB6834}",
        r"\definecolor{gridline}{HTML}{E1E0D9}",
        r"\definecolor{axisline}{HTML}{C3C2B7}",
        r"\definecolor{ink2}{HTML}{52514E}",
        r"\begin{figure}[t]",
        r"\centering",
        r"\begin{tikzpicture}",
        r"\begin{axis}[",
        r"  width=0.88\columnwidth, height=0.72\columnwidth,",
        r"  xmin=-0.2, xmax=0.28, ymin=-1.08, ymax=0.75,",
        r"  xlabel={$\Delta a(c)$: movement toward the class's own documents},",
        r"  ylabel={Share of headroom captured},",
        r"  axis lines=left, axis line style={axisline, -},",
        r"  grid=major, major grid style={gridline, line width=0.4pt},",
        r"  tick style={axisline}, tick label style={font=\footnotesize, text=ink2},",
        r"  label style={font=\footnotesize},",
        r"  xticklabel style={/pgf/number format/.cd, fixed, precision=2},",
        r"  legend style={font=\footnotesize, draw=none, fill=none, at={(0.5,1.02)}, anchor=south},",
        r"  legend columns=2, legend style={/tikz/every even column/.append style={column sep=10pt}},",
        r"  legend cell align=left, clip=false,",
        r"]",
        r"\draw[axisline, line width=0.5pt] (axis cs:0,-1.08) -- (axis cs:0,0.75);",
        r"\draw[axisline, line width=0.5pt] (axis cs:-0.2,0) -- (axis cs:0.28,0);",
        *plots,
        r"\end{axis}",
        r"\end{tikzpicture}",
        r"\caption{Each point is one class. Horizontal: how far elaborating its "
        r"description moved the class vector toward its own documents. Vertical: the "
        r"share of the available headroom in recall the class captured, "
        r"$(r_{\mathrm{rich}} - r_{\mathrm{terse}})/(1 - r_{\mathrm{terse}})$. "
        r"Spearman $\rho = \AlignRho$ over \NCLASSES\ classes ($p = \AlignP$), and "
        r"the ordering holds within each corpus. A class that falls below the plotted "
        r"range is drawn on the lower edge with its value.}",
        r"\label{fig:alignment}",
        r"\end{figure}",
        "",
    ]
    return "\n".join(lines)


def derived_macros(ablation: Dict, predictions: Dict, split: Dict, error_report: Dict,
                   search: Dict, verification: Dict, pilot: List[Dict], retired: Dict,
                   corpora: List[tuple]) -> List[str]:
    """Every remaining figure the prose quotes, each traced to its source file."""
    systems = {s["key"]: s for s in ablation["systems"]}
    full_top1 = systems["full"]["sector"]["top1_accuracy"]

    def accuracy(key, ids):
        docs = [d for d in predictions[key] if d["id"] in ids]
        return sum(d["predicted"] == d["true"] for d in docs) / len(docs)

    dev, test = set(split["dev"]), set(split["test"])
    seed_dev = accuracy("full", dev) - accuracy("no-seed-vector", dev)
    seed_test = accuracy("full", test) - accuracy("no-seed-vector", test)

    human = [r["true_sector"].strip() for r in pilot]
    silver = [r["silver_sector"].strip() for r in pilot]
    pilot_agree = sum(h == s for h, s in zip(human, silver)) / len(pilot)

    coding = error_report["manual_coding"]
    dist, n_coded = coding["distribution"], coding["n_coded"]
    scale = search["scale_and_calibration"]
    contrastive = search["selection_rules"]["20NG"]["contrastive"]
    translated = systems["translated-en"]
    (_, _, nace_align, _), (_, _, reuters_align, _), (_, _, news_align, _) = corpora

    return [
        r"\newcommand{\PilotN}{%d}" % len(pilot),
        r"\newcommand{\PilotAgree}{%s}" % share(pilot_agree),
        r"\newcommand{\PilotKappa}{%.3f}" % cohen_kappa(human, silver),
        r"\newcommand{\VerifyN}{%d}" % verification["n_verified"],
        r"\newcommand{\VerifyAgree}{%s}" % share(verification["raw_agreement"]),
        r"\newcommand{\VerifyKappa}{%.3f}" % verification["cohen_kappa"],
        r"\newcommand{\VerifyHighAgree}{%s}"
        % share(verification["by_labeller_confidence"]["high"]["agreement"]),
        r"\newcommand{\RetiredN}{%d}" % retired["retired"]["n"],
        r"\newcommand{\RetiredMedianChars}{%.0f}" % retired["retired"]["median_chars"],
        r"\newcommand{\CorpusMedianChars}{%.0f}" % retired["corpus"]["median_chars"],
        r"\newcommand{\RetiredBoilerplate}{%s\%%}" % pct(retired["retired"]["boilerplate_share"]),
        r"\newcommand{\CorpusBoilerplate}{%s\%%}" % pct(retired["corpus"]["boilerplate_share"]),
        r"\newcommand{\RetiredTopOne}{%s\%%}" % pct(retired["retired"]["reported_top1"]),
        r"\newcommand{\OldTaxonomyTopOne}{%s\%%}"
        % pct(systems["taxonomy-v1"]["sector"]["top1_accuracy"]),
        r"\newcommand{\SeedRemoval}{%+.1f}"
        % (100 * (systems["no-seed-vector"]["sector"]["top1_accuracy"] - full_top1)),
        r"\newcommand{\SeedRemovalP}{%.3f}" % systems["no-seed-vector"]["p_value_vs_full"],
        r"\newcommand{\SeedDevHelp}{%.1f}" % (100 * seed_dev),
        r"\newcommand{\SeedTestHurt}{%.1f}" % (-100 * seed_test),
        r"\newcommand{\TranslateGain}{%+.1f}"
        % (100 * (translated["sector"]["top1_accuracy"] - full_top1)),
        r"\newcommand{\TranslateP}{%.2f}" % translated["p_value_vs_full"],
        r"\newcommand{\SeedLeakShare}{%s}" % share(dist["seed_leakage"] / n_coded),
        r"\newcommand{\AmbigMultiShare}{%s}"
        % share((dist["ambiguous_sector_definition"] + dist["multi_sector_company"]) / n_coded),
        r"\newcommand{\ContrastiveNewsDelta}{%+.1f}" % contrastive["delta_pp"],
        r"\newcommand{\ContrastiveNewsP}{%.3f}" % contrastive["p_value"],
        r"\newcommand{\ElabShareNACE}{%s\%%}"
        % pct(scale["NACE"]["mixed"]["share_of_decisions_won_by_the_elaborated_half"]),
        r"\newcommand{\ElabShareNews}{%s\%%}"
        % pct(scale["20NG"]["mixed"]["share_of_decisions_won_by_the_elaborated_half"]),
        r"\newcommand{\FairShare}{%s}" % share(scale["NACE"]["mixed"]["fair_share"]),
        r"\newcommand{\ZScoreCost}{%.1f}"
        % (100 * (scale["NACE"]["rich"]["argmax"] - scale["NACE"]["rich"]["z_scored"])),
        r"\newcommand{\NaceAlignGain}{%+.3f}" % nace_align,
        r"\newcommand{\ReutersAlignGain}{%+.3f}" % reuters_align,
        r"\newcommand{\NewsAlignGain}{%+.3f}" % news_align,
    ]


