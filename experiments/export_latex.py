def pct(value) -> str:
    return "--" if value is None else f"{value * 100:.1f}"


def num(value, digits: int = 3) -> str:
    return "--" if value is None else f"{value:.{digits}f}"


def signed_pp(value) -> str:
    return "--" if value is None else f"${value * 100:+.1f}$"


def escape(text: str) -> str:
    for old, new in (("&", r"\&"), ("%", r"\%"), ("_", r"\_"), ("#", r"\#")):
        text = text.replace(old, new)
    # Times in T1 has none of these glyphs; left as Unicode they print as
    # empty boxes under XeTeX and fail outright under pdflatex.
    for old, new in (("−", "$-$"), ("↔", r"$\leftrightarrow$"), ("→", r"$\rightarrow$"),
                     ("↩", r"$\hookleftarrow$"), ("—", "---"), ("–", "--")):
        text = text.replace(old, new)
    return text


def share(value) -> str:
    """A rate quoted in prose as a whole percentage, e.g. 58\\%."""
    return "--" if value is None else f"{value * 100:.0f}\\%"


def cohen_kappa(a: List[str], b: List[str]):
    """Cohen's kappa, kept dependency-free so the paper builds without sklearn."""
    n = len(a)
    observed = sum(x == y for x, y in zip(a, b)) / n
    expected = sum((a.count(c) / n) * (b.count(c) / n) for c in set(a) | set(b))
    return None if expected >= 1 else (observed - expected) / (1 - expected)


def load_optional(name: str) -> Optional[Dict]:
    """A results file that only exists after an optional, separately run step."""
    path = RESULTS_DIR / f"{name}.json"
    return json.loads(path.read_text(encoding="utf-8")) if path.exists() else None


def load(name: str) -> Dict:
    path = RESULTS_DIR / f"{name}.json"
    if not path.exists():
        raise SystemExit(
            f"{path} is missing — run `make reproduce` before exporting tables."
        )
    return json.loads(path.read_text(encoding="utf-8"))


def baseline_table(systems: List[Dict], llm: Optional[Dict] = None) -> str:
    lines = [
        PREAMBLE,
        r"\begin{table*}[t]",
        r"\centering",
        r"\small",
        r"\begin{tabular}{lrrrrrr}",
        r"\toprule",
        r"System & Top-1 (\%) & 95\% CI & Top-3 (\%) & F1-macro & $\kappa$ & $p$ \\",
        r"\midrule",
    ]
    for s in systems:
        sector = s["sector"]
        ci = sector.get("top1_ci95") or [None, None]
        label = escape(s["label"])
        if s.get("is_oracle"):
            label += r"$^{\dagger}$"
        if s["key"] == "full":
            label = r"\textbf{" + label + "}"
        p = s.get("p_value_vs_full")
        lines.append(
            " & ".join(
                [
                    label,
                    pct(sector["top1_accuracy"]),
                    f"[{pct(ci[0])}, {pct(ci[1])}]",
                    pct(sector["top3_accuracy"]),
                    num(sector["f1_macro"]),
                    num(sector["cohen_kappa"]),
                    "--" if p is None else f"{p:.3f}",
                ]
            )
            + r" \\"
        )
    if llm:
        sector = llm["sector"]
        ci = sector["top1_ci95"]
        lines += [r"\midrule", " & ".join([
            r"\LLMModel, zero-shot$^{\ddagger}$",
            pct(sector["top1_accuracy"]),
            f"[{pct(ci[0])}, {pct(ci[1])}]",
            pct(sector["top3_accuracy"]),
            num(sector["f1_macro"]),
            num(sector["cohen_kappa"]),
            f"{llm['mcnemar_vs_full']['p_value']:.3f}",
        ]) + r" \\"]
    lines += [
        r"\bottomrule",
        r"\end{tabular}",
        r"\caption{Section classification on the held-out evaluation set "
        r"($n{=}\NEVAL$). Intervals are percentile bootstrap over "
        r"$10{,}000$ resamples; $p$ is an exact McNemar test against our full "
        r"system on the same documents, uncorrected (Holm-adjusted values are in "
        r"Appendix~\ref{app:effects}). $\dagger$ uses the gold label "
        r"distribution and is an oracle floor, not a competing method."
        + (r" $\ddagger$ an open instruction-tuned model asked directly for the section "
           r"with the prompt in Section~\ref{sec:llm}, run separately by "
           r"\texttt{make llm-baseline-local}." if llm else "")
        + "}",
        r"\label{tab:baselines}",
        r"\end{table*}",
        "",
    ]
    return "\n".join(lines)


def ablation_table(systems: List[Dict]) -> str:
    full = next((s for s in systems if s["key"] == "full"), None)
    base_top1 = full["sector"]["top1_accuracy"] if full else 0.0
    lines = [
        PREAMBLE,
        r"\begin{table}[t]",
        r"\centering",
        r"\footnotesize",
        r"\setlength{\tabcolsep}{4pt}",
        r"\begin{tabular}{@{}>{\raggedright\arraybackslash}p{3.9cm}rrr@{}}",
        r"\toprule",
        r"Variant & Top-1 & $\Delta$ & F1-macro \\",
        r"\midrule",
    ]
    for s in systems:
        sector = s["sector"]
        label = escape(s["label"])
        if s["key"] == "full":
            lines.append(
                " & ".join(
                    [r"\textbf{" + label + "}", pct(sector["top1_accuracy"]), "--",
                     num(sector["f1_macro"])]
                )
                + r" \\"
            )
            lines.append(r"\midrule")
            continue
        lines.append(
            " & ".join(
                [
                    label,
                    pct(sector["top1_accuracy"]),
                    signed_pp(sector["top1_accuracy"] - base_top1),
                    num(sector["f1_macro"]),
                ]
            )
            + r" \\"
        )
    lines += [
        r"\bottomrule",
        r"\end{tabular}",
        r"\caption{Component ablation. $\Delta$ is the change in Top-1 accuracy "
        r"against the full system in percentage points; $p$ is an exact McNemar test, "
        r"uncorrected (Holm-adjusted values are in Appendix~\ref{app:effects}). "
        r"Top-1 is a percentage, $\Delta$ percentage points.}",
        r"\label{tab:ablation}",
        r"\end{table}",
        "",
    ]
    return "\n".join(lines)


def error_table(report: Dict) -> str:
    flags = report.get("auto_flag_counts", {})
    lines = [
        PREAMBLE,
        r"\begin{table}[t]",
        r"\centering",
        r"\small",
        r"\begin{tabular}{lr}",
        r"\toprule",
        r"Property of the error & Count \\",
        r"\midrule",
    ]
    for flag, count in flags.items():
        lines.append(f"{escape(flag.replace('_', ' '))} & {count} " + r"\\")
    lines += [
        r"\bottomrule",
        r"\end{tabular}",
        r"\caption{Automatically determined properties of the "
        f"{report.get('n_errors', 0)} misclassified documents. "
        r"Manual categories are assigned against the codebook in the "
        r"accompanying repository.}",
        r"\label{tab:errors}",
        r"\end{table}",
        "",
    ]
    return "\n".join(lines)


def description_study_table(study: Dict) -> str:
    lines = [PREAMBLE, r"\begin{table}[t]", r"\centering", r"\small",
             r"\begin{tabular}{@{}>{\raggedright\arraybackslash}p{3.5cm}rrr@{}}", r"\toprule",
             r"Class descriptions & Top-1 & Top-3 & Words \\", r"\midrule"]
    for name, r in study["conditions"].items():
        label = escape(name)
        if "rewritten" in name or "definition" in name:
            label = r"\textbf{" + label + "}"
        lines.append(" & ".join([label, pct(r["top1_accuracy"]), pct(r["top3_accuracy"]),
                                 f"{r['mean_words_per_class']:.0f}"]) + r" \\")
    lines += [r"\bottomrule", r"\end{tabular}",
              r"\caption{Class descriptions on \NEVAL\ NACE documents, with the sector "
              r"vector built from the description alone. Rendering the same content in "
              r"German is the control: it isolates language from content. Top-1 and Top-3 are percentages.}",
              r"\label{tab:descriptions}", r"\end{table}", ""]
    return "\n".join(lines)


