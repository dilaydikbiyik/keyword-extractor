def second_device_macros(cpu: Dict, other: Dict) -> List[str]:
    """The same protocol on the machine's other device, to test the ordering."""
    first = {m["key"]: m for m in cpu["systems"]}
    second = {m["key"]: m for m in other["systems"]}
    shared = [k for k in second if k in first]
    order = sorted(shared, key=lambda k: first[k]["median_ms"])
    same = order == sorted(shared, key=lambda k: second[k]["median_ms"])
    lines = [
        r"\newcommand{\BenchOtherDevice}{%s}" % escape(other["encoder_device"]),
        r"\newcommand{\BenchOtherSystems}{%d}" % len(shared),
        r"\newcommand{\BenchOrderingHolds}{%s}" % ("unchanged" if same else "different"),
    ]
    for key, (stem, _, _) in BENCH_ROWS.items():
        if key in second:
            lines.append(r"\newcommand{\BenchOther%sMs}{%.1f}" % (stem, second[key]["median_ms"]))
    return lines


def holm_stat(value: float) -> str:
    return r"$p_{\mathrm{Holm}} < 0.001$" if value < 0.001 else f"$p_{{\\mathrm{{Holm}}}} = {value:.3f}$"


HOLM_CLAIMS = {
    "HolmAlignStat": ("Correlation", "alignment change vs. headroom captured"),
    "HolmRocchioRhoStat": ("Correlation", "label-free update (terse), per class"),
    "HolmLLMTopThreeStat": ("LLM", "full system vs. LLM, Top-3"),
    "HolmTfidfStat": ("System", "full system vs. TF-IDF"),
    "HolmVerifiedStat": ("Verified labels", "full system vs. previous taxonomy"),
    "HolmContrastiveStat": ("Selection rule", "20NG: contrastive margin"),
    "HolmMpnetNewsStat": ("Label-free update", "20NG: terse, mpnet"),
    "HolmBrownDefStat": ("Descriptions", "Brown: definitions"),
    "HolmBrownRhoStat": ("Correlation", "Brown, alignment"),
    "HolmArxivRhoStat": ("Correlation", "arXiv, alignment"),
    "HolmArxivDescStat": ("Descriptions", "arXiv: official descriptions"),
    "HolmEstimateRhoStat": ("Correlation", "label-free estimate vs. headroom"),
    "HolmExtendedContentStat": ("Descriptions", "second German set: definitions"),
    "HolmExtendedRhoStat": ("Correlation", "second German set, alignment"),
    "HolmLabseReutersStat": ("Label-free update", "Reuters: terse, LaBSE"),
    "HolmLabseRhoStat": ("Correlation", "label-free update (terse, LaBSE)"),
}


def effects_macros(effects: Dict) -> List[str]:
    lost = effects["lost_to_correction"]
    claims = []
    for macro, (group, prefix) in HOLM_CLAIMS.items():
        match = next((t for t in effects["tests"] if t["group"] == group and t["label"].startswith(prefix)), None)
        if match:
            claims.append(r"\newcommand{\%s}{%s}" % (macro, holm_stat(match["p_holm"])))
    return claims + [
        r"\newcommand{\EffectTests}{%d}" % effects["n_tests"],
        r"\newcommand{\EffectNominal}{%d}" % effects["nominally_significant"],
        r"\newcommand{\EffectHolm}{%d}" % effects["significant_after_holm"],
        r"\newcommand{\EffectLostList}{%s}" % ("none" if not lost else "; ".join(escape(x) for x in lost)),
    ]


def compute_macros(compute: Dict) -> List[str]:
    """What a complete reproduction costs, as recorded by run.py."""
    return [
        r"\newcommand{\ReproduceMinutes}{%d}" % max(1, round(compute["wall_clock_seconds"] / 60)),
        r"\newcommand{\ReproduceCPU}{%s}" % escape(compute["cpu"]),
        r"\newcommand{\ReproduceCores}{%d}" % compute["cpu_count"],
    ]


def macros(baselines: Dict, error_report: Dict, study: Dict, search: Dict,
           reuters: Dict, news: Dict, derived: List[str]) -> str:
    """Numbers the prose cites, as macros, so the text cannot drift either."""
    systems = {s["key"]: s for s in baselines["systems"]}
    conditions = list(study["conditions"].values())
    align = search["correlations"]["alignment_gain"]
    extra = [
        r"\newcommand{\DescTerse}{%s\%%}" % pct(conditions[0]["top1_accuracy"]),
        r"\newcommand{\DescTranslated}{%s\%%}" % pct(conditions[1]["top1_accuracy"]),
        r"\newcommand{\DescRich}{%s\%%}" % pct(conditions[2]["top1_accuracy"]),
        r"\newcommand{\LanguageEffect}{%+.1f}" % study["language_effect"]["gain_pp"],
        r"\newcommand{\LanguageP}{%.2f}" % study["language_effect"]["p_value"],
        r"\newcommand{\ContentEffect}{%+.1f}" % study["content_effect"]["gain_pp"],
        r"\newcommand{\AlignRho}{%+.3f}" % align["rho"],
        r"\newcommand{\AlignP}{%.3f}" % align["p"],
        r"\newcommand{\NCLASSES}{%d}" % search["n_classes"],
        r"\newcommand{\ReutersGain}{%+.1f}" % reuters["defining_the_class"]["gain_pp"],
        r"\newcommand{\ReutersCodeGain}{%+.1f}" % reuters["spelling_the_label_out"]["gain_pp"],
        r"\newcommand{\NewsGain}{%+.1f}" % news["defining_the_class"]["gain_pp"],
        r"\newcommand{\NewsP}{%.2f}" % news["defining_the_class"]["p_value"],
    ]
    full = systems.get("full", {}).get("sector", {})
    tfidf = systems.get("tfidf-nace", {}).get("sector", {})
    ci = full.get("top1_ci95") or [0, 0]
    return "\n".join(
        [
            PREAMBLE,
            r"\newcommand{\NEVAL}{%d}" % full.get("n", 0),
            r"\newcommand{\OursTopOne}{%s\%%}" % pct(full.get("top1_accuracy")),
            r"\newcommand{\OursTopThree}{%s\%%}" % pct(full.get("top3_accuracy")),
            r"\newcommand{\OursFOne}{%s}" % num(full.get("f1_macro")),
            r"\newcommand{\OursCI}{[%s, %s]}" % (pct(ci[0]), pct(ci[1])),
            r"\newcommand{\TfidfTopOne}{%s\%%}" % pct(tfidf.get("top1_accuracy")),
            r"\newcommand{\TfidfFOne}{%s}" % num(tfidf.get("f1_macro")),
            r"\newcommand{\NErrors}{%d}" % error_report.get("n_errors", 0),
            r"\newcommand{\CorpusSize}{9{,}993}",
            r"\newcommand{\EvalShareOfCorpus}{%.0f\%%}" % (100 * full.get("n", 0) / CORPUS_SIZE),
            r"\newcommand{\NSections}{21}",
            *extra,
            *derived,
            "",
        ]
    )


def main() -> int:
    TABLES_DIR.mkdir(parents=True, exist_ok=True)

    baselines = load("baselines")
    ablation = load("ablation")
    error_report = load("error_analysis")
    study = load("description_study")
    search = load("predictor_search")
    reuters = load("reuters")
    news = load("replication_20newsgroups")
    verification = load("verification_report")
    retired = load("retired_eval_set")
    predictions = load("ablation_predictions")
    split = json.loads((ROOT / "data" / "evaluation" / "split.json").read_text(encoding="utf-8"))
    with (RESULTS_DIR / "verification_sample_pilot.csv").open(encoding="utf-8") as handle:
        pilot = [r for r in csv.DictReader(handle) if r["true_sector"].strip()]

    corpora = corpus_effects(study, search, reuters, news)
    derived = derived_macros(ablation, predictions, split, error_report, search,
                             verification, pilot, retired, corpora)
    derived += robustness_macros(load("robustness"))
    derived += compute_macros(load("compute"))
    effects = load_optional("effect_sizes")
    if effects:
        derived += effects_macros(effects)
    studies = [(label, load_optional(prereg), load_optional(res), prefix)
               for label, prereg, res, prefix in ROCCHIO_STUDIES]
    studies = [s for s in studies if s[1] and s[2]]
    if studies:
        derived.append(r"\newcommand{\RocchioK}{%d}" % studies[0][2]["k"])
    for _, registered, result, prefix in studies:
        derived += rocchio_macros(registered, result, prefix)
    coding = load_optional("author_error_coding_report")
    if coding and coding.get("cohen_kappa") is not None:
        derived += [
            r"\newcommand{\ErrorCodingN}{%d}" % coding["n_coded"],
            r"\newcommand{\ErrorCodingAgree}{%.0f\%%}" % (100 * coding["agreement"]),
            r"\newcommand{\ErrorCodingKappa}{%.3f}" % coding["cohen_kappa"],
        ]
    mpnet_study = load_optional("description_study_paraphrase_multilingual_mpnet_base_v2")
    if mpnet_study:
        derived += [
            r"\newcommand{\MpnetContentEffect}{%+.1f}" % mpnet_study["content_effect"]["gain_pp"],
            r"\newcommand{\MpnetContentPStat}{%s}" % p_stat(mpnet_study["content_effect"]["p_value"]),
        ]
    labse_study = load_optional("description_study_LaBSE")
    if labse_study:
        derived += [
            r"\newcommand{\LabseContentEffect}{%+.1f}" % labse_study["content_effect"]["gain_pp"],
            r"\newcommand{\LabseContentPStat}{%s}" % p_stat(labse_study["content_effect"]["p_value"]),
            r"\newcommand{\LabseTopOne}{%s\%%}" % pct(
                labse_study["conditions"]["rewritten as NACE-style definitions"]["top1_accuracy"]),
        ]
    source = load_optional("description_source")
    if source:
        derived += description_source_macros(source)
    brown = load_optional("brown")
    if brown:
        derived += brown_macros(brown)
    arxiv = load_optional("arxiv")
    if arxiv:
        derived += arxiv_macros(arxiv)
    labelfree = load_optional("labelfree_predictor")
    if labelfree:
        derived += labelfree_macros(labelfree)
    extended = load_optional("extended_eval")
    if extended:
        derived += extended_macros(extended)
    sweep = load_optional("rocchio_sensitivity")
    if sweep:
        derived += sensitivity_macros(sweep)
    refs = load_optional("references")
    if refs:
        derived += references_macros(refs, ablation)
    bench = load_optional("benchmark")
    if bench:
        derived += benchmark_macros(bench)
        other = load_optional("benchmark_mps") or load_optional("benchmark_cuda")
        if other:
            derived += second_device_macros(bench, other)
    llm = load_optional("llm_baseline")
    if llm and llm.get("complete"):
        derived += llm_macros(llm)
    second = load_optional("llm_baseline_phi_3_mini_4k_instruct")
    if second and second.get("complete"):
        derived += second_llm_macros(second)
    with_definitions = load_optional("llm_baseline_definitions")
    if with_definitions and with_definitions.get("complete"):
        derived += llm_definitions_macros(with_definitions)
